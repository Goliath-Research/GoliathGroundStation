-- =====================================================================
-- GoliathGroundStation — durable integration-and-test (I&T) event log
-- Phase 3 DomainPrograms slice (issue #8). Provenance: authored in this repo;
-- not part of the Astra SQL Server migration in 01_schema.sql.
--
-- Purpose: time-series capture of sensor, actuator, and system variables
-- during avionics and rocket-engine integration and testing. Legacy testlog
-- l2r_* / r2l_* tables remain the exporter’s variable snapshot layout;
-- testlog.it_event is the normalized event stream DomainPrograms own.
--
-- Live OPC UA publish from the singleton gateway does NOT write here directly;
-- a batch logger action (claim loop) or operator campaign flushes durable rows.
-- See docs/domain-programs.md.
-- =====================================================================

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SET client_min_messages = warning;

CREATE TYPE testlog.it_event_source AS ENUM (
    'sensor',
    'actuator',
    'system'
);

COMMENT ON TYPE testlog.it_event_source IS
    'Origin of an I&T event row: measured sensor, commanded actuator, or ground/system meta.';

CREATE TABLE testlog.it_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    occurred_at timestamptz NOT NULL,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    source testlog.it_event_source NOT NULL,
    tag_id varchar(128),
    tag_name varchar(255) NOT NULL,
    value_json jsonb,
    value_numeric double precision,
    value_text text,
    test_id integer,
    campaign_id uuid,
    run_id uuid,
    operator_id varchar(128),
    session_id varchar(128),
    ingest_batch_id uuid,
    idempotency_key varchar(256),
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT pk_it_event PRIMARY KEY (id),
    CONSTRAINT it_event_value_present CHECK (
        value_json IS NOT NULL
        OR value_numeric IS NOT NULL
        OR value_text IS NOT NULL
    )
);

COMMENT ON TABLE testlog.it_event IS
    'Durable I&T events (sensors, actuators, system) for batch analysis and audit. '
    'Written by DomainProgram workers; not the live OPC telemetry bus.';

COMMENT ON COLUMN testlog.it_event.occurred_at IS
    'Event time on the vehicle, bench, or OPC source clock (UTC).';
COMMENT ON COLUMN testlog.it_event.recorded_at IS
    'Insert time in PostgreSQL (UTC).';
COMMENT ON COLUMN testlog.it_event.tag_id IS
    'Stable id when known (config field id, OPC node id string, etc.).';
COMMENT ON COLUMN testlog.it_event.tag_name IS
    'Human or OPC browse name at capture time.';
COMMENT ON COLUMN testlog.it_event.test_id IS
    'Optional link to config.test / campaign test id when scoped.';
COMMENT ON COLUMN testlog.it_event.campaign_id IS
    'Optional DomainProgram campaign or export job correlation uuid.';
COMMENT ON COLUMN testlog.it_event.run_id IS
    'Optional workflow instance or repeated-run uuid within a campaign.';
COMMENT ON COLUMN testlog.it_event.ingest_batch_id IS
    'Optional batch flush id from ground.it_event_flush_batch worker output.';
COMMENT ON COLUMN testlog.it_event.idempotency_key IS
    'Optional dedupe key (source + key) when replaying buffered events.';

CREATE UNIQUE INDEX it_event_idempotency_uq
    ON testlog.it_event (idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE INDEX it_event_occurred_at_idx ON testlog.it_event (occurred_at DESC);
CREATE INDEX it_event_source_occurred_idx ON testlog.it_event (source, occurred_at DESC);
CREATE INDEX it_event_tag_name_idx ON testlog.it_event (tag_name);
CREATE INDEX it_event_test_id_idx ON testlog.it_event (test_id) WHERE test_id IS NOT NULL;
CREATE INDEX it_event_campaign_run_idx ON testlog.it_event (campaign_id, run_id)
    WHERE campaign_id IS NOT NULL OR run_id IS NOT NULL;
